"""RuntimeManager — verify the python3 runtime on a node over SSH.

The platform **never installs anything** on a worker node. A ``RuntimeManager``
checks that ``python3`` is reachable on the node's PATH and returns its version
string so callers can gate execution on it.

Spark and Ray are **not** staged or used on workers: all heavy compute uses the
node's native ``python3`` and the stdlib-only scripts generated by
:mod:`ml_templates`.
"""
from __future__ import annotations

from typing import Optional

import structlog

from os_adapters.base import OSAdapter
from ssh_transport import SSHTransport

logger = structlog.get_logger(__name__)


class RuntimeManager:
    def __init__(
        self,
        transport: SSHTransport,
        adapter: OSAdapter,
        *,
        control_timeout: int = 30,
    ):
        self.transport = transport
        self.adapter = adapter
        self.control_timeout = control_timeout

        # Windows executes the Linux runtime through WSL2; everyone else native.
        self.wsl = adapter.os_type == "windows"
        if self.wsl:
            self.python = "python3"
        else:
            self.python = adapter.python_command()

    # -- shell wrapping ---------------------------------------------------
    def _wrap(self, command: str) -> str:
        """Wrap a POSIX shell command for the node (WSL on Windows)."""
        if self.wsl:
            import shlex
            return f"wsl -e bash -lc {shlex.quote(command)}"
        return command

    def _run(self, command: str, timeout: Optional[int] = None) -> dict:
        return self.transport.exec(self._wrap(command), timeout=timeout or self.control_timeout)

    # -- python -----------------------------------------------------------
    def ensure_python(self) -> dict:
        """Verify that python3 is available on the node.

        Raises ``RuntimeError`` when python3 is absent — every worker must
        have it; nothing will be installed by the platform.
        """
        res = self._run(f"{self.python} --version 2>&1")
        ok = res.get("exit_code") == 0 and "Python" in (res.get("stdout") or res.get("stderr") or "")
        if not ok:
            raise RuntimeError(
                "python3 is required on the node but was not found. "
                "Install Python 3 on the worker (no other dependencies needed)."
            )
        return {
            "python": self.python,
            "version": (res.get("stdout") or res.get("stderr") or "").strip(),
        }

    def prepare_runtime(self, kind: str) -> dict:
        """Ensure the requested runtime is ready. Only ``\"python\"`` is supported.

        Any other value raises ``ValueError`` — Spark and Ray are not installed
        on workers.
        """
        if kind == "python":
            return self.ensure_python()
        raise ValueError(
            f"Runtime kind {kind!r} is not supported. "
            "Workers require zero installation — only 'python' (python3) is valid."
        )
